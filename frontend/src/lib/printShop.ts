export async function uploadQrImage(file: File, token: string): Promise<{ qrUrl: string }> {
  const arrayBuffer = await file.arrayBuffer();
  const res = await fetch(`${API_BASE}/settings/qr`, {
    method: 'PUT',
    headers: {
      'Content-Type': file.type,
      'Authorization': `Bearer ${token}`,
    },
    body: arrayBuffer,
  });
  if (!res.ok) {
    const err = await res.json().catch(() => ({ error: 'upload_failed' }));
    throw new Error(err.error || 'upload_failed');
  }
  return res.json();
}

