export async function getPrintJobs(
  token: string,
  filters: { status?: string; method?: string; printType?: string; limit?: number; offset?: number } = {}
): Promise<PrintJob[]> {
  const params = new URLSearchParams();
  if (filters.status)    params.set('status', filters.status);
  if (filters.method)    params.set('method', filters.method);
  if (filters.printType) params.set('printType', filters.printType);
  if (filters.limit)     params.set('limit', String(filters.limit));
  if (filters.offset)    params.set('offset', String(filters.offset));
  const query = params.toString() ? `?${params.toString()}` : '';
  const data = await apiGet<{ jobs: any[] }>(`/jobs${query}`, token);
  return data.jobs.map(normalizeJob);
}

function normalizeJob(j: Record<string, unknown>): PrintJob {
  return {
    id: j.id as string,
    documentName: (j.document_name ?? j.documentName) as string,
    fileSizeBytes: Number(j.file_size_bytes ?? j.fileSizeBytes),
    fileType: (j.file_type ?? j.fileType) as string,
    pages: Number(j.pages),
    senderName: (j.sender_name ?? j.senderName) as string,
    printType: (j.print_type ?? j.printType) as PrintType,
    pricePerPage: parseFloat(String(j.price_per_page ?? j.pricePerPage)),
    totalAmount: parseFloat(String(j.total_amount ?? j.totalAmount)),
    paymentMethod: (j.payment_method ?? j.paymentMethod) as PaymentMethod,
    paymentStatus: (j.payment_status ?? j.paymentStatus) as PaymentStatus,
    paymentId: (j.payment_id ?? j.paymentId) as string | null,
    paidAt: (j.paid_at ?? j.paidAt) as string | null,
    createdAt: (j.created_at ?? j.createdAt) as string,
  };
}

